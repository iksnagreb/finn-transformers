def run(command: list[str], dry_run: bool) -> None:
	"""Run a repository command unless this is a dry run."""
	print(f"$ {' '.join(command)}")
	if not dry_run:
		subprocess.run(command, cwd=REPOSITORY_ROOT, check=True)


def git(*args: str) -> str:
	return subprocess.run(["git", *args], cwd=REPOSITORY_ROOT, check=True, capture_output=True, text=True).stdout


def experiment_task(experiment: dict) -> dict:
	return TASKS[experiment.get("task", "vision")]


def experiment_modes(experiment: dict) -> tuple[str, ...]:
	return (experiment["mode"],) if isinstance(experiment["mode"], str) else tuple(experiment["mode"])


def experiment_ref(experiment_id: str) -> str:
	refs = git("for-each-ref", "--format=%(objectname)", f"refs/exps/*/*/{experiment_id}").split()
	if len(refs) != 1:
		raise SystemExit(
			f"{experiment_id}: found {len(refs)} local experiment refs (fetch it with `dvc exp pull origin {experiment_id}`)"
		)
	return refs[0]


def measured_modes(experiment_id: str, task: dict) -> set[str]:
	"""Modes whose benchmark results were (re)written by this experiment's own commit."""
	ref = experiment_ref(experiment_id)
	plot_dir = (task["outputs"] / "plot").as_posix()
	changed = git("diff", "--name-only", f"{ref}^", ref, "--", plot_dir).split()
	pattern = re.compile(re.escape(plot_dir) + r"/([^/]+)/throughput_results\.json\.dvc$")
	return {match.group(1).lower() for path in changed if (match := pattern.match(path))}


def validate_experiments(experiment_ids: list[str]) -> None:
	"""Stop before applying anything if a configured mode was not measured by its experiment."""
	errors = []
	for experiment_id in experiment_ids:
		experiment = EXPERIMENTS[experiment_id]
		measured = measured_modes(experiment_id, experiment_task(experiment))
		missing = [mode for mode in experiment_modes(experiment) if mode not in measured]
		if missing:
			errors.append(
				f"  {experiment_id} ({experiment.get('task', 'vision')}/{experiment['model']} {experiment['power']}): "
				f"configured {', '.join(missing)} but the experiment measured {', '.join(sorted(measured)) or 'nothing'}"
			)
	if errors:
		raise SystemExit("Configured modes do not match the experiments:\n" + "\n".join(errors))


def check_md5(source: Path, experiment_id: str) -> None:
	"""Make sure the copied file is the one recorded by the experiment, not a stale leftover."""
	pointer = source.relative_to(REPOSITORY_ROOT).as_posix() + ".dvc"
	try:
		recorded = re.search(r"md5:\s*([0-9a-f]{32})", git("show", f"{experiment_ref(experiment_id)}:{pointer}")).group(1)
	except subprocess.CalledProcessError:
		print(f"    (no {pointer} in {experiment_id}, md5 not checked)")
		return
	actual = hashlib.md5(source.read_bytes()).hexdigest()
	if actual != recorded:
		raise RuntimeError(f"{source} does not match the md5 recorded in {experiment_id} ({actual} != {recorded})")


def throughput_correction_factor(batch_size: int, num_samples: int) -> float:
	"""Ratio of batches actually measured to batches the buggy script assumed."""
	return (num_samples // batch_size) / (BUGGY_ASSUMED_SAMPLES // batch_size)


def needs_throughput_correction(path: Path) -> bool:
	return path.name.startswith(THROUGHPUT_FILE_PREFIXES) and path.suffix == ".json"


def correct_throughput_file(path: Path, num_samples: int, dry_run: bool = False) -> None:
	"""Rescale the throughput values of one JSON file in place (idempotent)."""
	text = path.read_text()
	rows = json.loads(text)
	corrected = 0
	for row in rows:
		if row.get(CORRECTED_MARKER):
			continue
		factor = throughput_correction_factor(int(row["batch_size"]), num_samples)
		for key in THROUGHPUT_KEYS:
			if row.get(key) is not None:
				row[key] = float(row[key]) * factor
		row[CORRECTED_MARKER] = True
		corrected += 1
	print(f"    corrected throughput of {corrected}/{len(rows)} rows in {path.name}")
	if corrected and not dry_run:
		indent = 4 if '\n    "' in text else 2
		path.write_text(json.dumps(rows, indent=indent))


def experiment_has_ort_bug() -> bool:
	"""Check the measure script of the currently applied experiment."""
	return bool(BUGGY_NUM_BATCHES.search(ORT_MEASURE_SCRIPT.read_text()))


def acquire(experiment_id: str, experiment: dict[str, str | tuple[str, ...]], dry_run: bool) -> None:
	model = experiment["model"]
	power = experiment["power"]
	task = experiment_task(experiment)
	output_root = REPOSITORY_ROOT / task["outputs"] / "plot"
	model_root = task["data_root"] / model

	run(["dvc", "exp", "apply", experiment_id], dry_run)
	ort_bug = (not dry_run) and experiment_has_ort_bug()
	for mode in experiment_modes(experiment):
		destination = model_root / mode
		print(f"Acquiring {experiment_id} -> {destination.relative_to(REPOSITORY_ROOT)}")

		if not dry_run:
			destination.mkdir(parents=True, exist_ok=True)

		for source_name, destination_template in SOURCE_FILES.items():
			source = output_root / mode.upper() / source_name
			destination_name = destination_template.format(power=power)
			target = destination / destination_name
			print(f"  {source.relative_to(REPOSITORY_ROOT)} -> {target.relative_to(REPOSITORY_ROOT)}")
			if not dry_run:
				if not source.is_file():
					raise FileNotFoundError(f"Expected experiment output was not found: {source}")
				check_md5(source, experiment_id)
				shutil.copy2(source, target)
				if ort_bug and mode.startswith("ort_") and needs_throughput_correction(target):
					correct_throughput_file(target, task["num_samples"])

		for source_name, destination_template in OPTIONAL_SOURCE_FILES.items():
			source = output_root / mode.upper() / source_name
			target = destination / destination_template.format(power=power)
			print(f"  (optional) {source.relative_to(REPOSITORY_ROOT)} -> {target.relative_to(REPOSITORY_ROOT)}")
			if not dry_run and source.is_file():
				check_md5(source, experiment_id)
				shutil.copy2(source, target)
				if ort_bug and mode.startswith("ort_") and needs_throughput_correction(target):
					correct_throughput_file(target, task["num_samples"])

	for source_name in MODEL_SOURCE_FILES:
		source = output_root.parent / source_name
		target = model_root / source_name
		print(f"  (optional) {source.relative_to(REPOSITORY_ROOT)} -> {target.relative_to(REPOSITORY_ROOT)}")
		if not dry_run and source.is_file():
			target.parent.mkdir(parents=True, exist_ok=True)
			shutil.copy2(source, target)


def untracked_files() -> set[str]:
	return set(git("ls-files", "--others", "--exclude-standard", "-z").split("\0")) - {""}


def ensure_clean_checkout() -> None:
	"""The restore below resets everything outside summary_plots: refuse to lose uncommitted work."""
	dirty = git("status", "--porcelain", "--untracked-files=no", "--", ".", ":(exclude)summary_plots").strip()
	if dirty:
		raise SystemExit(
			"Uncommitted changes outside summary_plots would be reset by the restore step. "
			"Commit or stash them first:\n" + dirty
		)


def restore_checkout(untracked_before: set[str], dry_run: bool) -> None:
	"""Restore tracked experiment changes and remove untracked files the experiments added."""
	# Keep summary_plots out of the restore so freshly acquired data survives.
	run(["git", "restore", "--source=HEAD", "--staged", "--worktree", "--", ".", ":(exclude)summary_plots"], dry_run)
	if dry_run:
		print("(remove untracked files created by `dvc exp apply`)")
		return
	for name in sorted(untracked_files() - untracked_before):
		if name.startswith("summary_plots/"):
			continue
		path = REPOSITORY_ROOT / name
		print(f"  removing {name}")
		path.unlink()
		for parent in path.parents:
			if parent == REPOSITORY_ROOT or any(parent.iterdir()):
				break
			parent.rmdir()


def parse_args() -> argparse.Namespace:
	parser = argparse.ArgumentParser(description=__doc__)
	parser.add_argument(
		"experiments",
		nargs="*",
		metavar="EXPERIMENT_ID",
		help="Experiment IDs to acquire (default: all IDs in EXPERIMENTS).",
	)
	parser.add_argument(
		"--dry-run",
		action="store_true",
		help="Print DVC, copy, and restore operations without changing files.",
	)
	parser.add_argument(
		"--correct-existing",
		nargs="+",
		metavar="DIR",
		help=(
			"Apply the ONNX Runtime throughput correction in place to the throughput files in these "
			"already acquired ort_* directories, then exit. Rows already corrected are skipped."
		),
	)
	parser.add_argument(
		"--task",
		choices=sorted(TASKS),
		default="vision",
		help="Task of the --correct-existing directories (selects the evaluation set size).",
	)
	return parser.parse_args()


def main() -> None:
	args = parse_args()
	if args.correct_existing:
		for directory in map(Path, args.correct_existing):
			print(f"Correcting {directory}")
			for path in sorted(directory.glob("*.json")):
				if needs_throughput_correction(path):
					correct_throughput_file(path, TASKS[args.task]["num_samples"], args.dry_run)
		return

	experiment_ids = args.experiments or list(EXPERIMENTS)
	unknown_ids = [experiment_id for experiment_id in experiment_ids if experiment_id not in EXPERIMENTS]
	if unknown_ids:
		raise SystemExit(f"Unknown experiment ID(s): {', '.join(unknown_ids)}")

	validate_experiments(experiment_ids)
	if not args.dry_run:
		ensure_clean_checkout()
	untracked_before = set() if args.dry_run else untracked_files()
	try:
		for experiment_id in experiment_ids:
			acquire(experiment_id, EXPERIMENTS[experiment_id], args.dry_run)
	finally:
		restore_checkout(untracked_before, args.dry_run)


if __name__ == "__main__":
	main()
