def run(command: list[str], dry_run: bool) -> None:
	"""Run a repository command unless this is a dry run."""
	print(f"$ {' '.join(command)}")
	if not dry_run:
		subprocess.run(command, cwd=REPOSITORY_ROOT, check=True)


def throughput_correction_factor(batch_size: int) -> float:
	"""Ratio of batches actually measured to batches the buggy script assumed."""
	return (VISION_NUM_SAMPLES // batch_size) / (BUGGY_ASSUMED_SAMPLES // batch_size)


def needs_throughput_correction(path: Path) -> bool:
	return path.name.startswith(THROUGHPUT_FILE_PREFIXES) and path.suffix == ".json"


def correct_throughput_file(path: Path, dry_run: bool = False) -> None:
	"""Rescale the throughput values of one JSON file in place (idempotent)."""
	text = path.read_text()
	rows = json.loads(text)
	corrected = 0
	for row in rows:
		if row.get(CORRECTED_MARKER):
			continue
		factor = throughput_correction_factor(int(row["batch_size"]))
		for key in THROUGHPUT_KEYS:
			if row.get(key) is not None:
				row[key] = float(row[key]) * factor
		row[CORRECTED_MARKER] = True
		corrected += 1
	print(f"    corrected throughput of {corrected}/{len(rows)} rows in {path.name}")
	if corrected and not dry_run:
		indent = 4 if '\n    "' in text else 2
		path.write_text(json.dumps(rows, indent=indent))


def experiment_has_ort_bug() -> bool:
	"""Check the measure script of the currently applied experiment."""
	return bool(BUGGY_NUM_BATCHES.search(ORT_MEASURE_SCRIPT.read_text()))


def acquire(experiment_id: str, experiment: dict[str, str | tuple[str, ...]], dry_run: bool) -> None:
	model = experiment["model"]
	power = experiment["power"]

	run(["dvc", "exp", "apply", experiment_id], dry_run)
	ort_bug = (not dry_run) and experiment_has_ort_bug()
	modes = (experiment["mode"],) if isinstance(experiment["mode"], str) else experiment["mode"]
	for mode in modes:
		destination = DATA_ROOT / model / mode
		print(f"Acquiring {experiment_id} -> {destination.relative_to(REPOSITORY_ROOT)}")

		if not dry_run:
			destination.mkdir(parents=True, exist_ok=True)

		for source_name, destination_template in SOURCE_FILES.items():
			source = OUTPUT_ROOT / mode.upper() / source_name
			destination_name = destination_template.format(power=power)
			target = destination / destination_name
			print(f"  {source.relative_to(REPOSITORY_ROOT)} -> {target.relative_to(REPOSITORY_ROOT)}")
			if not dry_run:
				if not source.is_file():
					raise FileNotFoundError(f"Expected experiment output was not found: {source}")
				shutil.copy2(source, target)
				if ort_bug and mode.startswith("ort_") and needs_throughput_correction(target):
					correct_throughput_file(target)

		for source_name, destination_template in OPTIONAL_SOURCE_FILES.items():
			source = OUTPUT_ROOT / mode.upper() / source_name
			target = destination / destination_template.format(power=power)
			print(f"  (optional) {source.relative_to(REPOSITORY_ROOT)} -> {target.relative_to(REPOSITORY_ROOT)}")
			if not dry_run and source.is_file():
				shutil.copy2(source, target)
				if ort_bug and mode.startswith("ort_") and needs_throughput_correction(target):
					correct_throughput_file(target)

	for source_name in MODEL_SOURCE_FILES:
		source = OUTPUT_ROOT.parent / source_name
		target = DATA_ROOT / model / source_name
		print(f"  (optional) {source.relative_to(REPOSITORY_ROOT)} -> {target.relative_to(REPOSITORY_ROOT)}")
		if not dry_run and source.is_file():
			target.parent.mkdir(parents=True, exist_ok=True)
			shutil.copy2(source, target)


def restore_checkout(dry_run: bool) -> None:
	"""Restore tracked experiment changes and remove generated vision outputs."""
	# Keep summary_plots out of the restore so freshly acquired data survives.
	run(["git", "restore", "--source=HEAD", "--staged", "--worktree", "--", ".", ":(exclude)summary_plots"], dry_run)
	run(["git", "clean", "-fd", "--", "outputs/vision"], dry_run)


def parse_args() -> argparse.Namespace:
	parser = argparse.ArgumentParser(description=__doc__)
	parser.add_argument(
		"experiments",
		nargs="*",
		metavar="EXPERIMENT_ID",
		help="Experiment IDs to acquire (default: all IDs in EXPERIMENTS).",
	)
	parser.add_argument(
		"--dry-run",
		action="store_true",
		help="Print DVC, copy, and restore operations without changing files.",
	)
	parser.add_argument(
		"--correct-existing",
		nargs="+",
		metavar="DIR",
		help=(
			"Apply the ONNX Runtime throughput correction in place to the throughput files in these "
			"already acquired ort_* directories, then exit. Rows already corrected are skipped."
		),
	)
	return parser.parse_args()


def main() -> None:
	args = parse_args()
	if args.correct_existing:
		for directory in map(Path, args.correct_existing):
			print(f"Correcting {directory}")
			for path in sorted(directory.glob("*.json")):
				if needs_throughput_correction(path):
					correct_throughput_file(path, args.dry_run)
		return

	experiment_ids = args.experiments or list(EXPERIMENTS)
	unknown_ids = [experiment_id for experiment_id in experiment_ids if experiment_id not in EXPERIMENTS]
	if unknown_ids:
		raise SystemExit(f"Unknown experiment ID(s): {', '.join(unknown_ids)}")

	try:
		for experiment_id in experiment_ids:
			acquire(experiment_id, EXPERIMENTS[experiment_id], args.dry_run)
	finally:
		restore_checkout(args.dry_run)


if __name__ == "__main__":
	main()
