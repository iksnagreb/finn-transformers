"""Acquire vision and language benchmark JSON files from DVC experiments.

Run this file from any working directory, for example:

	python summary_plots/data_for_plots/data_acquisition.py --dry-run
	python summary_plots/data_for_plots/data_acquisition.py

The script applies each experiment, copies the files generated by that
experiment, and restores the checkout before moving to the next one.

Folder layout
	vision:   data_for_plots/<model>/<mode>/...            (e.g. base2/int8)
	language: data_for_plots/language/<model>/<mode>/...   (e.g. language/config1/ort_fp16)
	radioml:  data_for_plots/radioml/<model>/<mode>/...    (add experiments with "task": "radioml")

Checks (labels in docs or commit messages may be wrong, e.g. fp16/fp32 swapped)
	* Before anything is applied, every configured mode must have been measured
	  by that experiment, i.e. outputs/<task>/plot/<MODE>/throughput_results.json.dvc
	  changed in the experiment commit. Otherwise the script stops and names the
	  modes the experiment really measured.
	* Every copied file must match the md5 recorded in the experiment's .dvc file,
	  so no stale output of a previously applied experiment is copied.

ONNX Runtime throughput correction
	measure/measure_onnxruntime.py used to compute ``num_batches = int(7600 /
	batch_size)``, the size of the language test set, instead of
	``len(test_loader)``. The benchmark iterates the full evaluation set
	(drop_last), so the stored throughput of every ``ort_*`` mode is too low by
	``(N // bs) / (7600 // bs)`` with N = 10000 (vision), 9530 (language) or
	10000 (radioml), see doku/bug_7600. When the applied
	experiment still contains that bug, the copied ``throughput_*`` and
	``latency_throughput_*`` files (and ``power_throughput_*`` if present) are
	rescaled. Corrected rows get ``"num_batches_corrected": true`` so the
	correction is never applied twice.

	Files that were acquired earlier and whose experiments are no longer listed
	(e.g. unsigned_int8/, base_no_warnings/) can be corrected in place:

		python summary_plots/data_for_plots/data_acquisition.py --correct-existing \\
			summary_plots/data_for_plots/unsigned_int8/base2/ort_int8

	(add ``--task language`` for language directories)
"""

